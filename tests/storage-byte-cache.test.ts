import { afterEach, expect, it, vi } from 'vitest'
import { StorageByteCache } from '@/lib/snowflake/storage-byte-cache'

afterEach(() => {
  vi.useRealTimers()
  vi.unstubAllEnvs()
})
it('bounds the entire process cache under 1,000 upload identities, not each identity', () => {
  const cache = new StorageByteCache(32 * 1024 ** 2)
  const data = Buffer.alloc(64 * 1024, 7)
  for (let i = 0; i < 1000; i++) {
    cache.set(`upload-${i}`, data)
    expect(cache.bytes).toBeLessThanOrEqual(cache.maxBytes)
    expect(cache.size).toBeLessThanOrEqual(cache.maxEntries)
  }
  expect(cache.has('upload-0')).toBe(false)
  expect(cache.take('upload-999')!.equals(data)).toBe(true)
  expect(cache.has('upload-999')).toBe(false)
  const large = Buffer.alloc(8 * 1024 ** 2)
  for (let i = 0; i < 5; i++) cache.set(`large-${i}`, large)
  expect(cache.bytes).toBe(32 * 1024 ** 2)
  expect(cache.size).toBe(4)
  cache.set('oversized', Buffer.alloc(8 * 1024 ** 2 + 1))
  expect(cache.has('oversized')).toBe(false)
})
it('copies input and repeated reads, consumes chunks, and expires without extending lifetime', () => {
  vi.useFakeTimers()
  const cache = new StorageByteCache(10, 2, 10)
  const input = Buffer.from('abc')
  cache.set('a', input, 100)
  input.fill(0)
  cache.get('a')!.fill(0)
  expect(cache.get('a')!.toString()).toBe('abc')
  vi.advanceTimersByTime(100)
  expect(cache.take('a')).toBeUndefined()
  expect(cache.bytes).toBe(0)
  cache.set('a', Buffer.from('ok'))
  cache.clear()
  expect(cache.get('a')).toBeUndefined()
})
it('can bypass reuse without changing the durable path', () => {
  const cache = new StorageByteCache()
  cache.set('a', Buffer.from('a'))
  vi.stubEnv('STORAGE_BYTE_REUSE_ENABLED', 'false')
  expect(cache.take('a')).toBeUndefined()
  expect(cache.get('a')).toBeUndefined()
  cache.set('b', Buffer.from('b'))
  expect(cache.has('b')).toBe(false)
})
it('shares one budget and byte handoff across duplicate Next route/background module copies', async () => {
  const first = await import('@/lib/snowflake/storage-byte-cache')
  first.storageByteCache.clear()
  first.storageByteCache.set('handoff', Buffer.from('durable bytes'))
  vi.resetModules()
  const second = await import('@/lib/snowflake/storage-byte-cache')
  expect(second.storageByteCache).toBe(first.storageByteCache)
  expect(second.storageByteCache.take('handoff')?.toString()).toBe('durable bytes')
  expect(first.storageByteCache.bytes).toBe(0)
})
