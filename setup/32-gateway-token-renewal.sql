-- Dedicated gateway key authenticates the renewal operation. The existing PAT
-- remains restricted to PERSONAL_PHOTOS_GATEWAY_ACCESS, which cannot rotate keys.
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS PERSONAL_PHOTOS_TOKEN_RENEWAL;
GRANT ROLE PERSONAL_PHOTOS_TOKEN_RENEWAL TO ROLE SYSADMIN;
GRANT ROLE PERSONAL_PHOTOS_TOKEN_RENEWAL TO USER PERSONAL_PHOTOS_GATEWAY;
GRANT MODIFY PROGRAMMATIC AUTHENTICATION METHODS ON USER PERSONAL_PHOTOS_GATEWAY TO ROLE PERSONAL_PHOTOS_TOKEN_RENEWAL;
ALTER AUTHENTICATION POLICY PERSONAL_MEDIA.APP.PHOTOS_GATEWAY_AUTH SET AUTHENTICATION_METHODS=('PROGRAMMATIC_ACCESS_TOKEN','KEYPAIR');
