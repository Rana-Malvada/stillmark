-- REVIEW ONLY: creating Cortex services has ongoing cost. Do not run without approval.
-- Existing objects are preserved. Verify their schemas/attributes before deploying.
CREATE TABLE IF NOT EXISTS PERSONAL_MEDIA.DATA.PHOTO_SEARCH_DATA (
 PHOTO_ID NUMBER, EVENT_ID NUMBER, SOURCE_FILENAME VARCHAR,
 DISPLAY_STAGE_PATH VARCHAR, THUMBNAIL_STAGE_PATH VARCHAR, DATE_TAKEN TIMESTAMP_NTZ,
 CAMERA_MAKE VARCHAR, CAMERA_MODEL VARCHAR, LENS_MODEL VARCHAR, SOFTWARE VARCHAR, ARTIST VARCHAR,
 FOCAL_LENGTH VARCHAR, APERTURE VARCHAR, SHUTTER_SPEED VARCHAR, ISO NUMBER, FLASH_USED BOOLEAN,
 WHITE_BALANCE VARCHAR, EXPOSURE_MODE VARCHAR, SCENE_CAPTURE_TYPE VARCHAR,
 LATITUDE FLOAT, LONGITUDE FLOAT, ALTITUDE FLOAT, COUNTRY VARCHAR, REGION VARCHAR,
 CITY VARCHAR, LOCATION_NAME VARCHAR, IPTC_KEYWORDS VARCHAR, IPTC_HEADLINE VARCHAR, CAPTION VARCHAR,
 AI_DESCRIPTION VARCHAR, AI_TAGS VARCHAR, FAVORITE BOOLEAN, RATING NUMBER,
 SEARCH_TEXT VARCHAR, UPDATED_AT TIMESTAMP_NTZ, EVENT_NAME VARCHAR,
 EVENT_MONTH NUMBER, EVENT_YEAR NUMBER, EVENT_LOCATION VARCHAR
);
CREATE TABLE IF NOT EXISTS PERSONAL_MEDIA.DATA.EVENT_SEARCH_DATA (
 EVENT_ID NUMBER, EVENT_NAME VARCHAR, EVENT_MONTH NUMBER, EVENT_YEAR NUMBER,
 LOCATION VARCHAR, PHOTO_COUNT NUMBER, SEARCH_TEXT VARCHAR, UPDATED_AT TIMESTAMP_NTZ
);
CREATE CORTEX SEARCH SERVICE IF NOT EXISTS PERSONAL_MEDIA.DATA.PHOTO_SEARCH_SERVICE
 ON SEARCH_TEXT ATTRIBUTES EVENT_ID
 WAREHOUSE = COMPUTE_WH TARGET_LAG = '1 hour'
 AS SELECT * FROM PERSONAL_MEDIA.DATA.PHOTO_SEARCH_DATA WHERE SEARCH_TEXT IS NOT NULL;
CREATE CORTEX SEARCH SERVICE IF NOT EXISTS PERSONAL_MEDIA.DATA.EVENT_SEARCH_SERVICE
 ON SEARCH_TEXT ATTRIBUTES EVENT_ID
 WAREHOUSE = COMPUTE_WH TARGET_LAG = '1 hour'
 AS SELECT * FROM PERSONAL_MEDIA.DATA.EVENT_SEARCH_DATA WHERE SEARCH_TEXT IS NOT NULL;

-- Manual-only indexing after initial creation. Keep SERVING available.
ALTER CORTEX SEARCH SERVICE PERSONAL_MEDIA.DATA.PHOTO_SEARCH_SERVICE SUSPEND INDEXING;
ALTER CORTEX SEARCH SERVICE PERSONAL_MEDIA.DATA.EVENT_SEARCH_SERVICE SUSPEND INDEXING;
