-- Bootstrap as ACCOUNTADMIN. This role is never granted to gallery visitors.
CREATE ROLE IF NOT EXISTS PERSONAL_PHOTOS_RUNTIME
 COMMENT='Personal Photos backend execution; no account administrator inheritance';
GRANT ROLE PERSONAL_PHOTOS_RUNTIME TO ROLE SYSADMIN;
GRANT USAGE ON DATABASE PERSONAL_MEDIA TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT USAGE ON SCHEMA PERSONAL_MEDIA.APP TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT USAGE ON SCHEMA PERSONAL_MEDIA.RAW TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT USAGE ON SCHEMA PERSONAL_MEDIA.DATA TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT READ,WRITE ON STAGE PERSONAL_MEDIA.RAW.PHOTO_FILES TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE PERSONAL_MEDIA.DATA.PHOTO_SEARCH_DATA TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE PERSONAL_MEDIA.DATA.EVENT_SEARCH_DATA TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT USAGE,OPERATE ON CORTEX SEARCH SERVICE PERSONAL_MEDIA.DATA.PHOTO_SEARCH_SERVICE TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT USAGE,OPERATE ON CORTEX SEARCH SERVICE PERSONAL_MEDIA.DATA.EVENT_SEARCH_SERVICE TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT USE AI FUNCTION AI_COMPLETE ON ACCOUNT TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT DATABASE ROLE SNOWFLAKE.USAGE_VIEWER TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT DATABASE ROLE SNOWFLAKE.GOVERNANCE_VIEWER TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT DATABASE ROLE SNOWFLAKE.SECURITY_VIEWER TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT USAGE ON INTEGRATION PERSONAL_PHOTOS_EAI TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT USAGE ON INTEGRATION PERSONAL_PHOTOS_AUTH0_EAI TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT USAGE ON INTEGRATION PERSONAL_PHOTOS_TRAVEL_EAI TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT READ ON SECRET PERSONAL_MEDIA.APP.GATEWAY_SIGNING TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT READ ON SECRET PERSONAL_MEDIA.APP.AUTH0_MANAGEMENT TO ROLE PERSONAL_PHOTOS_RUNTIME;
-- PG_APP_SECRET is created separately without persisting its password here.
GRANT READ ON SECRET PERSONAL_MEDIA.APP.PG_APP_SECRET TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT READ ON ARTIFACT REPOSITORY PERSONAL_MEDIA.APP.PERSONAL_PHOTOS_REPO TO ROLE PERSONAL_PHOTOS_RUNTIME;
-- Needed for the existing in-app provisioning feature, not MANAGE GRANTS.
-- Identity administration is isolated by setup/62 and finalized by setup/63.
-- Do not grant CREATE USER/CREATE ROLE to the web runtime.
-- Network-policy usage belongs only to PERSONAL_PHOTOS_IDENTITY_OWNER.
-- Creation privilege is revoked after the replacement service has been created.
GRANT CREATE APPLICATION SERVICE ON SCHEMA PERSONAL_MEDIA.APP TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT BIND SERVICE ENDPOINT ON ACCOUNT TO ROLE PERSONAL_PHOTOS_RUNTIME;
