-- Offline, bounded historical backfill only. Never imported by application reporting.
-- Known legacy signatures are frozen to query/function IDs after review.
SELECT a.QUERY_ID,a.FUNCTION_NAME,
CASE
 WHEN (h.QUERY_TEXT ILIKE '%PERSONAL_MEDIA.DATA._CORTEX_SEARCH_SOURCE_PHOTO_SEARCH_SERVICE_%'
    OR h.QUERY_TEXT ILIKE '%PERSONAL_MEDIA.DATA._CORTEX_SEARCH_SOURCE_EVENT_SEARCH_SERVICE_%')
    AND (a.FUNCTION_NAME ILIKE '%EMBED%' OR a.MODEL_NAME ILIKE '%embed%') THEN 'search_indexing'
 WHEN a.FUNCTION_NAME ILIKE '%EMBED%' THEN 'search_ai'
 WHEN h.QUERY_TEXT ILIKE '%/* personal-photos:video_ai */%' THEN 'video_ai'
 WHEN h.QUERY_TEXT ILIKE '%/* personal-photos:photo_ai */%' THEN 'photo_ai'
 WHEN h.QUERY_TEXT ILIKE '%AI_COMPLETE(%' AND h.QUERY_TEXT ILIKE '%@PERSONAL_MEDIA.RAW.PHOTO_FILES%'
   AND (h.QUERY_TEXT ILIKE '%Analyze this video%' OR h.QUERY_TEXT ILIKE '%Analyze this single personal video%' OR h.QUERY_TEXT ILIKE '%Describe this video%'
     OR h.QUERY_TEXT ILIKE '%16384%PARSE_JSON(?)%') THEN 'video_ai'
 WHEN h.QUERY_TEXT ILIKE '%AI_COMPLETE(%' AND h.QUERY_TEXT ILIKE '%@PERSONAL_MEDIA.RAW.PHOTO_FILES%'
   AND (h.QUERY_TEXT ILIKE '%Analyze this photo%'
     OR UPPER(TRIM(h.QUERY_TEXT))='SELECT AI_COMPLETE(?, ?, TO_FILE(''@PERSONAL_MEDIA.RAW.PHOTO_FILES'', ?)) AS RESULT') THEN 'photo_ai'
 ELSE 'other_ai' END AS KIND
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY a
LEFT JOIN SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY h ON h.QUERY_ID=a.QUERY_ID
WHERE a.START_TIME>=DATEADD(day,-30,TO_TIMESTAMP_TZ('{cutoff}'))
AND a.START_TIME<TO_TIMESTAMP_TZ('{cutoff}')
AND a.WAREHOUSE_ID IN (SELECT DISTINCT WAREHOUSE_ID FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
 WHERE WAREHOUSE_NAME='COMPUTE_WH' AND START_TIME>=DATEADD(day,-31,TO_TIMESTAMP_TZ('{cutoff}')))
GROUP BY 1,2,3
