-- Reviewed reference for the face scan job. Apply as ACCOUNTADMIN only after review.
-- The Postgres role exists from migration 202610072000; set its password first and
-- store the same value in the secret below (never in source control).
CREATE COMPUTE POOL IF NOT EXISTS PERSONAL_PHOTOS_FACE_CPU
  MIN_NODES=1 MAX_NODES=1 INSTANCE_FAMILY=CPU_X64_M
  AUTO_RESUME=FALSE AUTO_SUSPEND_SECS=900 INITIALLY_SUSPENDED=TRUE
  COMMENT='Personal Photos face scan jobs';
CREATE SECRET IF NOT EXISTS PERSONAL_MEDIA.APP.FACE_WORKER_PG_SECRET TYPE=PASSWORD
  USERNAME='personal_photos_face_worker' PASSWORD='<set at apply time>';
CREATE EXTERNAL ACCESS INTEGRATION IF NOT EXISTS PERSONAL_PHOTOS_FACE_EAI
  ALLOWED_NETWORK_RULES=(PERSONAL_MEDIA.APP.PG_EGRESS_RULE)
  ALLOWED_AUTHENTICATION_SECRETS=(PERSONAL_MEDIA.APP.FACE_WORKER_PG_SECRET) ENABLED=TRUE;

-- Job identity: runs the container. No pool OPERATE: it cannot resume or suspend.
CREATE ROLE IF NOT EXISTS PERSONAL_PHOTOS_FACE_WORKER;
GRANT USAGE ON DATABASE PERSONAL_MEDIA TO ROLE PERSONAL_PHOTOS_FACE_WORKER;
GRANT USAGE ON SCHEMA PERSONAL_MEDIA.APP TO ROLE PERSONAL_PHOTOS_FACE_WORKER;
GRANT USAGE ON SCHEMA PERSONAL_MEDIA.RAW TO ROLE PERSONAL_PHOTOS_FACE_WORKER;
GRANT CREATE SERVICE ON SCHEMA PERSONAL_MEDIA.APP TO ROLE PERSONAL_PHOTOS_FACE_WORKER;
GRANT READ ON IMAGE REPOSITORY PERSONAL_MEDIA.APP.PHOTOS_REPO TO ROLE PERSONAL_PHOTOS_FACE_WORKER;
GRANT READ ON STAGE PERSONAL_MEDIA.RAW.PHOTO_FILES TO ROLE PERSONAL_PHOTOS_FACE_WORKER;
GRANT READ,WRITE ON STAGE PERSONAL_MEDIA.RAW.DERIVED_FILES TO ROLE PERSONAL_PHOTOS_FACE_WORKER;
GRANT READ ON SECRET PERSONAL_MEDIA.APP.FACE_WORKER_PG_SECRET TO ROLE PERSONAL_PHOTOS_FACE_WORKER;
GRANT USAGE ON INTEGRATION PERSONAL_PHOTOS_FACE_EAI TO ROLE PERSONAL_PHOTOS_FACE_WORKER;
GRANT USAGE ON COMPUTE POOL PERSONAL_PHOTOS_FACE_CPU TO ROLE PERSONAL_PHOTOS_FACE_WORKER;

-- Launcher identity: owns the public control procedure and may resume/suspend the
-- face pool only. It has no rights on the video GPU pool.
CREATE ROLE IF NOT EXISTS PERSONAL_PHOTOS_FACE_LAUNCHER;
GRANT USAGE ON DATABASE PERSONAL_MEDIA TO ROLE PERSONAL_PHOTOS_FACE_LAUNCHER;
GRANT USAGE ON SCHEMA PERSONAL_MEDIA.APP TO ROLE PERSONAL_PHOTOS_FACE_LAUNCHER;
GRANT OPERATE,MONITOR ON COMPUTE POOL PERSONAL_PHOTOS_FACE_CPU TO ROLE PERSONAL_PHOTOS_FACE_LAUNCHER;

-- Same hierarchy as the video roles: administrators inherit, nobody else.
GRANT ROLE PERSONAL_PHOTOS_FACE_WORKER TO ROLE SYSADMIN;
GRANT ROLE PERSONAL_PHOTOS_FACE_LAUNCHER TO ROLE SYSADMIN;
