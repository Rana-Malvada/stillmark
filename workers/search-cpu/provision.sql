-- Dedicated, finite OCR/visual-embedding and saved-ranking compute.
-- Create suspended; only an explicitly started search batch resumes it.
CREATE COMPUTE POOL IF NOT EXISTS PERSONAL_PHOTOS_SEARCH_CPU
  MIN_NODES=1 MAX_NODES=1 INSTANCE_FAMILY=CPU_X64_M
  AUTO_RESUME=FALSE AUTO_SUSPEND_SECS=900 INITIALLY_SUSPENDED=TRUE
  COMMENT='Personal Photos OCR, visual embeddings and saved search rankings';
CREATE ROLE IF NOT EXISTS PERSONAL_PHOTOS_SEARCH_WORKER;
GRANT USAGE ON DATABASE PERSONAL_MEDIA TO ROLE PERSONAL_PHOTOS_SEARCH_WORKER;
GRANT USAGE ON SCHEMA PERSONAL_MEDIA.APP TO ROLE PERSONAL_PHOTOS_SEARCH_WORKER;
GRANT USAGE ON SCHEMA PERSONAL_MEDIA.RAW TO ROLE PERSONAL_PHOTOS_SEARCH_WORKER;
GRANT CREATE SERVICE ON SCHEMA PERSONAL_MEDIA.APP TO ROLE PERSONAL_PHOTOS_SEARCH_WORKER;
GRANT READ ON IMAGE REPOSITORY PERSONAL_MEDIA.APP.PHOTOS_REPO TO ROLE PERSONAL_PHOTOS_SEARCH_WORKER;
GRANT READ ON STAGE PERSONAL_MEDIA.RAW.PHOTO_FILES TO ROLE PERSONAL_PHOTOS_SEARCH_WORKER;
GRANT READ ON SECRET PERSONAL_MEDIA.APP.SEARCH_WORKER_PG_SECRET TO ROLE PERSONAL_PHOTOS_SEARCH_WORKER;
CREATE EXTERNAL ACCESS INTEGRATION IF NOT EXISTS PERSONAL_PHOTOS_SEARCH_EAI ALLOWED_NETWORK_RULES=(PERSONAL_MEDIA.APP.PG_EGRESS_RULE) ALLOWED_AUTHENTICATION_SECRETS=(PERSONAL_MEDIA.APP.SEARCH_WORKER_PG_SECRET) ENABLED=TRUE;
GRANT USAGE ON INTEGRATION PERSONAL_PHOTOS_SEARCH_EAI TO ROLE PERSONAL_PHOTOS_SEARCH_WORKER;
GRANT USAGE ON COMPUTE POOL PERSONAL_PHOTOS_SEARCH_CPU TO ROLE PERSONAL_PHOTOS_SEARCH_WORKER;
GRANT ROLE PERSONAL_PHOTOS_SEARCH_WORKER TO ROLE SYSADMIN;
GRANT USAGE,OPERATE,MONITOR ON COMPUTE POOL PERSONAL_PHOTOS_SEARCH_CPU TO ROLE PERSONAL_PHOTOS_RUNTIME;
GRANT ROLE PERSONAL_PHOTOS_SEARCH_WORKER TO ROLE PERSONAL_PHOTOS_RUNTIME;
