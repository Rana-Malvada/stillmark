-- Reviewed reference for the face scan job. Apply as ACCOUNTADMIN only after review.
-- The Postgres role exists from migration 202610072000; set its password first and
-- store the same value in the secret below (never in source control).
CREATE COMPUTE POOL IF NOT EXISTS {{FACE_POOL}}
  MIN_NODES=1 MAX_NODES=1 INSTANCE_FAMILY={{FACE_INSTANCE_FAMILY}}
  AUTO_RESUME=FALSE AUTO_SUSPEND_SECS=900 INITIALLY_SUSPENDED=TRUE
  COMMENT='Personal Photos face scan jobs';
CREATE SECRET IF NOT EXISTS {{DATABASE}}.{{APP_SCHEMA}}.{{FACE_SECRET}} TYPE=PASSWORD
  USERNAME='{{FACE_PG_USER}}' PASSWORD='<set at apply time>';
CREATE EXTERNAL ACCESS INTEGRATION IF NOT EXISTS {{FACE_EAI}}
  ALLOWED_NETWORK_RULES=({{DATABASE}}.{{APP_SCHEMA}}.{{PG_NETWORK_RULE}})
  ALLOWED_AUTHENTICATION_SECRETS=({{DATABASE}}.{{APP_SCHEMA}}.{{FACE_SECRET}}) ENABLED=TRUE;

-- Job identity: runs the container. No pool OPERATE: it cannot resume or suspend.
CREATE ROLE IF NOT EXISTS {{FACE_ROLE}};
GRANT USAGE ON DATABASE {{DATABASE}} TO ROLE {{FACE_ROLE}};
GRANT USAGE ON SCHEMA {{DATABASE}}.{{APP_SCHEMA}} TO ROLE {{FACE_ROLE}};
GRANT USAGE ON SCHEMA {{DATABASE}}.{{RAW_SCHEMA}} TO ROLE {{FACE_ROLE}};
GRANT CREATE SERVICE ON SCHEMA {{DATABASE}}.{{APP_SCHEMA}} TO ROLE {{FACE_ROLE}};
GRANT READ ON IMAGE REPOSITORY {{DATABASE}}.{{APP_SCHEMA}}.{{IMAGE_REPOSITORY}} TO ROLE {{FACE_ROLE}};
GRANT READ ON STAGE {{DATABASE}}.{{RAW_SCHEMA}}.{{PHOTO_STAGE}} TO ROLE {{FACE_ROLE}};
GRANT READ,WRITE ON STAGE {{DATABASE}}.{{RAW_SCHEMA}}.{{DERIVED_STAGE}} TO ROLE {{FACE_ROLE}};
GRANT READ ON SECRET {{DATABASE}}.{{APP_SCHEMA}}.{{FACE_SECRET}} TO ROLE {{FACE_ROLE}};
GRANT USAGE ON INTEGRATION {{FACE_EAI}} TO ROLE {{FACE_ROLE}};
GRANT USAGE ON COMPUTE POOL {{FACE_POOL}} TO ROLE {{FACE_ROLE}};

-- Launcher identity: owns the public control procedure and may resume/suspend the
-- face pool only. It has no rights on the video GPU pool.
CREATE ROLE IF NOT EXISTS {{FACE_LAUNCHER_ROLE}};
GRANT USAGE ON DATABASE {{DATABASE}} TO ROLE {{FACE_LAUNCHER_ROLE}};
GRANT USAGE ON SCHEMA {{DATABASE}}.{{APP_SCHEMA}} TO ROLE {{FACE_LAUNCHER_ROLE}};
GRANT OPERATE,MONITOR ON COMPUTE POOL {{FACE_POOL}} TO ROLE {{FACE_LAUNCHER_ROLE}};

-- Same hierarchy as the video roles: administrators inherit, nobody else.
GRANT ROLE {{FACE_ROLE}} TO ROLE SYSADMIN;
GRANT ROLE {{FACE_LAUNCHER_ROLE}} TO ROLE SYSADMIN;
